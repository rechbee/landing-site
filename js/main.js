function currentMap(file) {
  if (!file || file === 'index.html') return 'home';
  return file.replace('.html', '');
}

function applyLanguage(lang) {
  const dict = I18N[lang] || I18N['pt-BR'];
  document.documentElement.setAttribute('lang', lang);
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.dataset.i18n;
    if (dict[key] !== undefined && el.getAttribute('type') !== 'text') {
      el.textContent = dict[key];
    }
  });

  const toggle = document.getElementById('langToggle');
  if (toggle) toggle.textContent = lang === 'pt-BR' ? 'EN' : 'PT';

  const page = document.body.dataset.page;
  if (page && TITLES[page]) {
    document.title = TITLES[page][lang === 'pt-BR' ? 0 : 1];
  }
}

function initFilters() {
  const filters = document.querySelectorAll('.filters button');
  if (!filters.length) return;

  filters.forEach((btn) => {
    btn.addEventListener('click', () => {
      filters.forEach((b) => b.classList.toggle('active', b === btn));
      const cat = btn.dataset.filter;
      document.querySelectorAll('.work').forEach((w) => {
        const match = cat === 'all' || w.dataset.cat === cat;
        w.classList.toggle('hide', !match);
      });
    });
  });
}

function initForm() {
  const form = document.getElementById('contactForm');
  const success = document.getElementById('formSuccess');
  const select = document.getElementById('planning');

  const params = new URLSearchParams(location.search);
  const u = params.get('u');
  if (u && select) {
    select.value = u;
    select.classList.add('has-value');
  }

  if (select) {
    select.addEventListener('change', () => {
      select.classList.toggle('has-value', !!select.value);
    });
  }

  if (form && success) {
    form.addEventListener('submit', (e) => {
      e.preventDefault();
      form.reset();
      if (select) select.classList.remove('has-value');
      success.classList.remove('hide');
      success.scrollIntoView({ behavior: 'smooth', block: 'center' });
      setTimeout(() => success.classList.add('hide'), 6000);
    });
  }
}

function initReveal() {
  const els = document.querySelectorAll('.reveal');
  if (!els.length || !('IntersectionObserver' in window)) {
    els.forEach((el) => el.classList.add('is-in'));
    return;
  }
  const io = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add('is-in');
        io.unobserve(entry.target);
      }
    });
  }, { threshold: 0.12, rootMargin: '0px 0px -8% 0px' });
  els.forEach((el) => io.observe(el));
}